// Builds src/components/scene/landmarks/sites.ts: where the wind turbines,
// transmitter towers and lighthouses stand, in NZTM, with the ground height
// under each.
//
//   node scripts/landmarks/build_sites.mjs [--osm cached.json]
//
// Positions come from OpenStreetMap (© OpenStreetMap contributors, ODbL),
// most of them traced from LINZ Topo50 (CC BY 4.0). Ground heights are read
// from the terrain tiles in public/terrain, so run this after build_tiles.py.

import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { createGroundSampler, toNztm } from "../lib/geo.mjs";

const ROOT = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "../.."
);

const TERRAIN = path.join(ROOT, "public/terrain");
const OUT = path.join(ROOT, "src/components/scene/landmarks/sites.ts");

const QUERY = `[out:json][timeout:60];
(
  node["generator:source"="wind"](-41.40,174.55,-41.15,174.85);
  way["man_made"="tower"]["name"="Kaukau TV/FM transmitter"];
  node(296684884);
  node(id:1907945529,1052816306,1052817586,6035642212);
);
out center body;`;

/** OSM node of the lattice communication tower on Mt Victoria (Topo50 7640592). */
const MT_VICTORIA_NODE = 296684884;

/** OSM nodes of the lighthouses, by the site each becomes. */
const LIGHTHOUSE_NODES = new Map([
  [1907945529, "pencarrow"],
  [1052816306, "pencarrowLower"],
  [1052817586, "baringHead"],
  [6035642212, "pointHalswell"],
]);

async function loadOsm() {
  const cached = process.argv.indexOf("--osm");

  if (cached > 0)
    return JSON.parse(await readFile(process.argv[cached + 1], "utf8"));

  const response = await fetch("https://overpass-api.de/api/interpreter", {
    method: "POST",
    headers: {
      "User-Agent": "joshbarr.com scene builder",
      Accept: "application/json",
      "Content-Type": "application/x-www-form-urlencoded",
    },
    body: new URLSearchParams({ data: QUERY }),
  });

  if (!response.ok) throw new Error(`overpass: ${response.status}`);

  return response.json();
}

const { groundHeight: sampleGround } = await createGroundSampler(TERRAIN);

async function groundHeight(easting, northing) {
  const height = await sampleGround(easting, northing);

  if (height === undefined) {
    throw new Error(`no terrain under ${easting}, ${northing}`);
  }

  return height;
}

// --- Sort the nodes into sites. ---

const osm = await loadOsm();

const sites = {
  westWind: [],
  millCreek: [],
  brooklyn: [],
  kaukau: [],
  mtVictoria: [],
  pencarrow: [],
  pencarrowLower: [],
  baringHead: [],
  pointHalswell: [],
};

for (const element of osm.elements) {
  // Footprints mapped as ways are placed at their centre.
  const node = { ...element, ...element.center };
  const { tags = {} } = node;
  let site;

  if (node.id === MT_VICTORIA_NODE) site = "mtVictoria";
  else if (LIGHTHOUSE_NODES.has(node.id)) site = LIGHTHOUSE_NODES.get(node.id);
  else if (tags.name === "Kaukau TV/FM transmitter") site = "kaukau";
  else if (tags["generator:source"] !== "wind") continue;
  else if (tags.name === "Brooklyn Wind Turbine") site = "brooklyn";
  // Mill Creek is the cluster on the Ohariu ridges, north-east of West Wind.
  else if (node.lat > -41.222 && node.lon > 174.715) site = "millCreek";
  else site = "westWind";

  const [e, n] = toNztm(node.lat, node.lon);
  const ground = await groundHeight(e, n);
  sites[site].push({ id: node.id, e, n, ground });
}

const expected = {
  westWind: 62,
  millCreek: 26,
  brooklyn: 1,
  kaukau: 1,
  mtVictoria: 1,
  pencarrow: 1,
  pencarrowLower: 1,
  baringHead: 1,
  pointHalswell: 1,
};

for (const [name, count] of Object.entries(expected)) {
  if (sites[name].length !== count) {
    console.warn(`${name}: expected ${count}, found ${sites[name].length}`);
  }
}

const format = (list) =>
  list
    .sort((a, b) => a.id - b.id)
    .map(
      ({ e, n, ground }) =>
        `  [${e.toFixed(1)}, ${n.toFixed(1)}, ${ground.toFixed(1)}],`
    )
    .join("\n");

const single = (list) => {
  const [{ e, n, ground }] = list;

  return `[${e.toFixed(1)}, ${n.toFixed(1)}, ${ground.toFixed(1)}]`;
};

await writeFile(
  OUT,
  `// Generated by scripts/landmarks/build_sites.mjs. Do not edit.
//
// Positions © OpenStreetMap contributors (ODbL), largely from LINZ Topo50
// (CC BY 4.0). Each entry is [easting, northing, ground] in NZTM2000 metres;
// ground is the bare-earth DEM height, before the terrain's vertical scale.

export type Site = [easting: number, northing: number, ground: number];

/** Meridian's West Wind, Mākara: 62 Siemens SWT-2.3-82 VS. */
export const WEST_WIND: Site[] = [
${format(sites.westWind)}
];

/** Meridian's Mill Creek, Ohariu: 26 Siemens SWT-2.3-82 VS. */
export const MILL_CREEK: Site[] = [
${format(sites.millCreek)}
];

/** The Brooklyn turbine: an Enercon E-44 since 2016. */
export const BROOKLYN: Site = ${single(sites.brooklyn)};

/** Kordia's TV/FM transmitter on Mt Kaukau. */
export const KAUKAU: Site = ${single(sites.kaukau)};

/** The lattice communications tower by the Mt Victoria lookout. */
export const MT_VICTORIA: Site = ${single(sites.mtVictoria)};

/** The first Pencarrow lighthouse (1859), on the head; dark since 1935. */
export const PENCARROW: Site = ${single(sites.pencarrow)};

/** Pencarrow's lower light (1906), by the shore below it. */
export const PENCARROW_LOWER: Site = ${single(sites.pencarrowLower)};

/** Baring Head lighthouse (1935), the harbour's landfall light. */
export const BARING_HEAD: Site = ${single(sites.baringHead)};

/** Point Halswell light, at the tip of the Miramar peninsula. */
export const POINT_HALSWELL: Site = ${single(sites.pointHalswell)};
`
);

