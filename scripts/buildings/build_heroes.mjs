// Builds src/components/scene/buildings/heroes.ts: footprints of the
// waterfront's landmark buildings, which are floodlit at night (see
// floodlights.ts), in NZTM.
//
//   node scripts/buildings/build_heroes.mjs [--osm cached.json]
//
// Footprints from OpenStreetMap (© OpenStreetMap contributors, ODbL). The
// WCC models carry no names, so the scene finds these by where they stand.

import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { toNztm } from "../lib/geo.mjs";

const ROOT = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "../.."
);

const OUT = path.join(ROOT, "src/components/scene/buildings/heroes.ts");

/** Key in the scene, OSM way, and the name it should carry there. */
// prettier-ignore
const HEROES = [
  { key: "tePapa", way: 190557095, name: "Museum of New Zealand Te Papa Tongarewa" },
  { key: "takina", way: 1028184544, name: "Tākina - Wellington Convention and Exhibition Centre" },
  { key: "michaelFowler", way: 190555300, name: "Michael Fowler Centre" },
  // Queens Wharf.
  { key: "museum", way: 250856271, name: "Wellington Museum" },
  { key: "harbourBoard", way: 250855232, name: "Wellington Habour Board Offices building" },
  { key: "shed6", way: 38138812, name: "Shed 6" },
  { key: "shed5", way: 38138809, name: "Shed 5" },
  { key: "queensWharf", way: 38139157, name: "3 Queens Wharf" },
  { key: "meridian", way: 250856273, name: "Meridian Building" },
  // Deloitte House.
  { key: "deloitte", way: 256663669, name: "20 Customhouse Quay" },
];

const QUERY = `[out:json][timeout:60];
way(id:${HEROES.map(({ way }) => way).join(",")});
out geom tags;`;

async function loadOsm() {
  const cached = process.argv.indexOf("--osm");

  if (cached > 0)
    return JSON.parse(await readFile(process.argv[cached + 1], "utf8"));

  const response = await fetch("https://overpass-api.de/api/interpreter", {
    method: "POST",
    headers: {
      "User-Agent": "joshbarr.com scene builder",
      Accept: "application/json",
      "Content-Type": "application/x-www-form-urlencoded",
    },
    body: new URLSearchParams({ data: QUERY }),
  });

  if (!response.ok) throw new Error(`overpass: ${response.status}`);

  return response.json();
}

const osm = await loadOsm();
const ways = new Map(osm.elements.map((e) => [e.id, e]));

const footprints = HEROES.map(({ key, way, name }) => {
  const element = ways.get(way);

  if (!element) throw new Error(`${key}: way ${way} is missing`);

  if (element.tags?.name !== name) {
    throw new Error(`${key}: way ${way} is now "${element.tags?.name}"`);
  }

  // Closed ways repeat their first node last; the polygon closes itself.
  const ring = element.geometry
    .slice(0, -1)
    .map(({ lat, lon }) => toNztm(lat, lon));

  return { key, name, ring };
});

const point = ([e, n]) => `[${e.toFixed(1)}, ${n.toFixed(1)}]`;

await writeFile(
  OUT,
  `// Generated by scripts/buildings/build_heroes.mjs. Do not edit.
//
// Footprints © OpenStreetMap contributors (ODbL), as [easting, northing] in
// NZTM2000 metres.

/** The waterfront's landmark buildings, by key. */
// prettier-ignore
export const HEROES = {
${footprints
  .map(
    ({ key, name, ring }) =>
      `  // ${name}\n  ${key}: [${ring.map(point).join(", ")}],`
  )
  .join("\n")}
} satisfies Record<string, [number, number][]>;
`
);

console.log(`${footprints.length} footprints → ${path.relative(ROOT, OUT)}`);
