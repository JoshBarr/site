// Builds public/rail/stations.json: where Metlink's trains call, for the
// scene's trains to stand at and nowhere else.
//
//   node scripts/trains/build_stations.mjs [--gtfs cached.zip]
//
// The stations come from Metlink's GTFS timetable: every stop a rail trip
// (route_type 2) calls at, by its stop_times. A station's point is the
// timetable's: the platform's, or the middle of the station's for those
// with several. Rebuild when a new timetable opens or closes a station.

import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { strFromU8, unzipSync } from "three/examples/jsm/libs/fflate.module.js";
import { toNztm } from "../lib/geo.mjs";

const ROOT = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "../.."
);

const OUT_DIR = path.join(ROOT, "public/rail");

const GTFS = "https://static.opendata.metlink.org.nz/v1/gtfs/full.zip";

/** GTFS's route type for rail. */
const RAIL = "2";

/** As lib/trains.ts's MAP_BOUNDS, NZTM [west, south, east, north]. */
const MAP_BOUNDS = [1715232, 5395232, 1780768, 5460768];

async function loadGtfs() {
  const cached = process.argv.indexOf("--gtfs");

  if (cached > 0) {
    return new Uint8Array(await readFile(process.argv[cached + 1]));
  }

  const response = await fetch(GTFS);

  if (!response.ok) throw new Error(`gtfs: ${response.status}`);

  return new Uint8Array(await response.arrayBuffer());
}

/** Rows of a CSV file as arrays, the header first. */
function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let quoted = false;

  for (let i = 0; i < text.length; i++) {
    const c = text[i];

    if (quoted) {
      if (c === '"' && text[i + 1] === '"') {
        field += '"';
        i++;
      } else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ",") {
      row.push(field);
      field = "";
    } else if (c === "\n" || c === "\r") {
      if (c === "\r" && text[i + 1] === "\n") i++;
      row.push(field);

      if (row.length > 1 || row[0]) rows.push(row);
      row = [];
      field = "";
    } else field += c;
  }

  if (field || row.length) rows.push([...row, field]);

  return rows;
}

const files = unzipSync(await loadGtfs(), {
  filter: ({ name }) =>
    ["routes.txt", "trips.txt", "stop_times.txt", "stops.txt"].includes(name),
});

/** Each row of a file, with the columns asked for by name. */
function table(name, columns) {
  const [header, ...body] = parseCsv(strFromU8(files[name]));
  const keys = header.map((k) => k.replace(/^﻿/, ""));
  const at = columns.map((c) => keys.indexOf(c));

  return body.map((row) => at.map((i) => row[i]));
}

const routes = new Set(
  table("routes.txt", ["route_id", "route_type"])
    .filter(([, type]) => type === RAIL)
    .map(([id]) => id)
);

const trips = new Set(
  table("trips.txt", ["trip_id", "route_id"])
    .filter(([, route]) => routes.has(route))
    .map(([id]) => id)
);

const called = new Set(
  table("stop_times.txt", ["trip_id", "stop_id"])
    .filter(([trip]) => trips.has(trip))
    .map(([, stop]) => stop)
);

// A station's platforms, where trips call at each, are one station, in the
// middle of them.
const platforms = new Map();

for (const [id, name, lat, lon] of table("stops.txt", [
  "stop_id",
  "stop_name",
  "stop_lat",
  "stop_lon",
])) {
  if (!called.has(id)) continue;
  const key = name.replace(/ Station$/, "");

  if (!platforms.has(key)) platforms.set(key, []);
  platforms.get(key).push(toNztm(Number(lat), Number(lon)));
}

const [west, south, east, north] = MAP_BOUNDS;

const stations = [];

for (const [name, points] of platforms) {
  const mean = (k) => points.reduce((sum, p) => sum + p[k], 0) / points.length;
  const [e, n] = [Math.round(mean(0)), Math.round(mean(1))];

  if (e > west && e < east && n > south && n < north) {
    stations.push([name, e, n]);
  }
}

stations.sort(([a], [b]) => a.localeCompare(b));

await mkdir(OUT_DIR, { recursive: true });

await writeFile(
  path.join(OUT_DIR, "stations.json"),
  JSON.stringify({
    // Generated by scripts/trains/build_stations.mjs from Metlink's GTFS.
    // [name, easting, northing], NZTM2000 metres.
    stations,
  })
);

console.log(`${stations.length} stations on the map`);
