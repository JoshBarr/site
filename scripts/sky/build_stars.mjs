// Builds src/components/scene/sky/stars.ts: the stars of the major
// constellations' figures, and every star brighter than BRIGHT, for the
// scene's night sky.
//
// Stars and figures from d3-celestial (Olaf Frohn, BSD-3-Clause), whose
// stars are from the HYG database (David Nash, CC BY-SA). "Major" is
// d3-celestial's rank 1 and 2 figures: Orion, Scorpius, Crux, Carina and
// the like, not the faint filler between them.

import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const ROOT = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "../.."
);

const CACHE = path.join(ROOT, ".cache/sky");
const OUT = path.join(ROOT, "src/components/scene/sky/stars.ts");

const DATA =
  "https://raw.githubusercontent.com/ofrohn/d3-celestial/master/data";

/** d3-celestial's figure ranks to keep: 1 the best known, 3 the faintest. */
const RANKS = new Set(["1", "2"]);

/** Any star brighter than this is kept, figure or not (magnitude). */
const BRIGHT = 5;

/** A figure's vertex further than this from any star is left out, degrees. */
const MATCH = 0.05;

async function cached(name) {
  const file = path.join(CACHE, name);

  try {
    return JSON.parse(await readFile(file, "utf8"));
  } catch {
    const response = await fetch(`${DATA}/${name}`);

    if (!response.ok) throw new Error(`${name}: ${response.status}`);
    const text = await response.text();

    await mkdir(CACHE, { recursive: true });
    await writeFile(file, text);

    return JSON.parse(text);
  }
}

const stars = (await cached("stars.6.json")).features;
const figures = (await cached("constellations.lines.json")).features;

/** Angular distance on the sky, degrees, near enough for small ones. */
function apart([ra1, dec1], [ra2, dec2]) {
  const dRa = ((ra1 - ra2 + 540) % 360) - 180;

  return Math.hypot(dRa * Math.cos((dec1 * Math.PI) / 180), dec1 - dec2);
}

const kept = new Set();
let unmatched = 0;

for (const figure of figures) {
  if (!RANKS.has(figure.properties.rank)) continue;

  for (const line of figure.geometry.coordinates) {
    for (const vertex of line) {
      let best = null;
      let distance = Infinity;

      for (const star of stars) {
        const d = apart(star.geometry.coordinates, vertex);

        if (d < distance) [best, distance] = [star, d];
      }

      if (distance > MATCH) unmatched++;
      else kept.add(best);
    }
  }
}

for (const star of stars) {
  if (star.properties.mag < BRIGHT) kept.add(star);
}

// Brightest first, so the faint end can be cut on a phone.
const rows = [...kept]
  .map(({ geometry, properties }) => {
    // d3-celestial gives right ascension as -180..180 degrees.
    const [ra, dec] = geometry.coordinates;

    return [(ra + 360) % 360, dec, properties.mag];
  })
  .sort((a, b) => a[2] - b[2]);

const values = rows
  .map(([ra, dec, mag]) => `${ra.toFixed(3)},${dec.toFixed(3)},${mag}`)
  .join(",\n  ");

await mkdir(path.dirname(OUT), { recursive: true });

await writeFile(
  OUT,
  `// Generated by scripts/sky/build_stars.mjs. Do not edit.
//
// The stars of the major constellations' figures and every star brighter
// than magnitude ${BRIGHT}, brightest first: from d3-celestial (Olaf Frohn,
// BSD-3-Clause), after the HYG database (David Nash, CC BY-SA).

/** Per star: right ascension and declination (J2000, degrees), magnitude. */
export const STARS = [
  ${values},
];
`
);

console.log(
  `${rows.length} stars, magnitude ${rows[0][2]} to ${rows.at(-1)[2]}; ` +
    `${unmatched} figure vertices matched no star`
);
