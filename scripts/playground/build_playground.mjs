// Builds src/components/scene/playground/site.ts: where Te Aro Mahana, the
// playground in Frank Kitts Park, sits in NZTM, and the bare ground under it
// on a grid, so its painted surface can lie on the terrain.
//
//   node scripts/playground/build_playground.mjs
//
// The anchor is OpenStreetMap's playground (way 1157164172, © OpenStreetMap
// contributors, ODbL), rounded to the metre; the equipment in layout.ts is
// placed from it. Ground heights are read from the terrain tiles in
// public/terrain, so run this after build_tiles.py.

import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { createGroundSampler, toNztm } from "../lib/geo.mjs";

const ROOT = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "../.."
);

const TERRAIN = path.join(ROOT, "public/terrain");
const OUT = path.join(ROOT, "src/components/scene/playground/site.ts");

/** Near the middle of the playground, latitude and longitude. */
const CENTRE = [-41.28642, 174.77875];

/** Grid spacing, m, and its extent east and north of the anchor. */
const STEP = 2;
const WEST = -24;
const EAST = 26;
const SOUTH = -22;
const NORTH = 18;

const [easting, northing] = toNztm(...CENTRE).map(Math.round);
const { groundHeight } = await createGroundSampler(TERRAIN);
const rows = [];

for (let n = SOUTH; n <= NORTH; n += STEP) {
  const row = [];

  for (let e = WEST; e <= EAST; e += STEP) {
    const height = await groundHeight(easting + e, northing + n);

    if (height === undefined) {
      throw new Error(`no terrain under ${easting + e}, ${northing + n}`);
    }

    row.push(Math.round(height * 100) / 100);
  }

  rows.push(`  ${row.join(", ")},`);
}

const columns = (EAST - WEST) / STEP + 1;

await writeFile(
  OUT,
  `// Generated by scripts/playground/build_playground.mjs. Do not edit.
//
// Anchor from OpenStreetMap (© OpenStreetMap contributors, ODbL); ground
// from the terrain's bare-earth DEM, before the terrain's vertical scale.

/** NZTM2000 easting and northing the playground's layout is measured from. */
export const ANCHOR: [number, number] = [${easting}, ${northing}];

/**
 * Bare ground, m, every ${STEP} m: rows south to north from ${SOUTH} m, ${columns}
 * columns west to east from ${WEST} m, in grid metres from ANCHOR.
 */
export const GROUND = {
  step: ${STEP},
  west: ${WEST},
  south: ${SOUTH},
  columns: ${columns},
  // prettier-ignore
  heights: [
${rows.join("\n")}
  ],
};
`
);

console.log(`wrote ${OUT}`);
